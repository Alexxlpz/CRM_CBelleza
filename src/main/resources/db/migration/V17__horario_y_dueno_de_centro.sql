-- Horario de apertura propio de cada centro y dueño del centro.
--  · center_opening_hours: tramos en los que el centro abre, por día de la semana (1 = lunes ... 7 = domingo).
--    Un día con dos tramos es jornada partida (p. ej. 09:00-14:00 y 16:00-20:00); un día sin tramos, cerrado.
--    Los centros que ya existían reciben el horario que había para todos: lunes a viernes de 9:00 a 20:00.
--  · centers.owner_id: el trabajador que dio de alta el centro. Es el único que cambia sus datos, horario,
--    foto, carta, tarjeta de puntos y reservas automáticas. En los centros que ya existían es el trabajador
--    con el mismo correo que el centro (el alta usa el del responsable) o, si no hay, el primero que se creó.

CREATE TABLE center_opening_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id   BIGINT   NOT NULL,
    day_of_week INT      NOT NULL,
    opens_at    TIME     NOT NULL,
    closes_at   TIME     NOT NULL,
    CONSTRAINT ck_center_opening_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_center_opening_hours_range CHECK (closes_at > opens_at),
    CONSTRAINT fk_center_opening_hours_center FOREIGN KEY (center_id) REFERENCES centers (id) ON DELETE CASCADE
);
CREATE INDEX ix_center_opening_hours_center ON center_opening_hours (center_id, day_of_week);

INSERT INTO center_opening_hours (center_id, day_of_week, opens_at, closes_at)
SELECT c.id, d.day_of_week, TIME '09:00:00', TIME '20:00:00'
FROM centers c
CROSS JOIN (SELECT 1 AS day_of_week UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5) d;

