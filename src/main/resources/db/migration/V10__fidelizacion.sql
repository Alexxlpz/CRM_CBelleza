-- Fidelización por puntos, configurable por centro desde «Mi Centro».
--  · loyalty_mode: OFF (desactivada), PER_EURO (puntos por euro gastado) o PER_ITEM (puntos por servicio o producto).
--  · loyalty_points_per_unit: puntos por euro o por servicio/unidad de producto.
--  · loyalty_reward_points y loyalty_reward_text: cuántos puntos hacen falta y qué se regala.
--  · loyalty_since: desde cuándo suma; las citas anteriores no dan puntos.
-- loyalty_movements es el saldo de cada cliente en cada centro: entradas por tratamiento o producto y salidas por canje.
-- Los puntos se guardan al ganarlos, así un cambio de configuración no altera lo ya ganado.

ALTER TABLE centers ADD COLUMN loyalty_mode VARCHAR(16) DEFAULT 'OFF' NOT NULL;
ALTER TABLE centers ADD CONSTRAINT ck_centers_loyalty_mode CHECK (loyalty_mode IN ('OFF', 'PER_EURO', 'PER_ITEM'));
ALTER TABLE centers ADD COLUMN loyalty_points_per_unit INT DEFAULT 1 NOT NULL;
ALTER TABLE centers ADD COLUMN loyalty_reward_points INT DEFAULT 100 NOT NULL;
ALTER TABLE centers ADD COLUMN loyalty_reward_text VARCHAR(200);
ALTER TABLE centers ADD COLUMN loyalty_since TIMESTAMP(6);

CREATE TABLE loyalty_movements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id       BIGINT       NOT NULL,
    client_id       BIGINT       NOT NULL,
    points          INT          NOT NULL,
    reason          VARCHAR(16)  NOT NULL,
    description     VARCHAR(255),
    appointment_id  BIGINT,
    product_sale_id BIGINT,
    created_at      TIMESTAMP(6) NOT NULL,
    created_by_id   BIGINT,
    CONSTRAINT ck_loyalty_movements_reason CHECK (reason IN ('TREATMENT', 'PRODUCT', 'REDEMPTION')),
    -- Una cita solo da puntos una vez
    CONSTRAINT uk_loyalty_movements_appointment UNIQUE (appointment_id),
    CONSTRAINT fk_loyalty_movements_center FOREIGN KEY (center_id) REFERENCES centers (id),
    CONSTRAINT fk_loyalty_movements_client FOREIGN KEY (client_id) REFERENCES users (id),
    CONSTRAINT fk_loyalty_movements_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE SET NULL,
    CONSTRAINT fk_loyalty_movements_sale FOREIGN KEY (product_sale_id) REFERENCES product_sales (id) ON DELETE CASCADE,
    CONSTRAINT fk_loyalty_movements_created_by FOREIGN KEY (created_by_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_loyalty_movements_center_client ON loyalty_movements (center_id, client_id);
