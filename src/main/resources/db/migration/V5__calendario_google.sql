-- Sincronización de la agenda con Google Calendar (opcional, por trabajador).
-- Cada fila es un trabajador que ha activado la sincronización: guarda el token de actualización
-- de Google (cifrado con GOOGLE_TOKEN_KEY) y el calendario «Cuquora» creado en su cuenta.
-- En appointments se apunta el evento de Google de cada cita para poder moverlo o borrarlo después.

CREATE TABLE google_calendar_links (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id               BIGINT       NOT NULL,
    google_email            VARCHAR(255),
    encrypted_refresh_token VARCHAR(2048) NOT NULL,
    calendar_id             VARCHAR(255) NOT NULL,
    connected_at            TIMESTAMP    NOT NULL,
    CONSTRAINT uk_google_calendar_links_worker UNIQUE (worker_id),
    CONSTRAINT fk_google_calendar_links_worker FOREIGN KEY (worker_id) REFERENCES users (id) ON DELETE CASCADE
);

ALTER TABLE appointments ADD COLUMN google_event_id VARCHAR(255);
