-- Fotos y vídeos en el resumen del tratamiento: para enseñar al resto del equipo algo que se entiende mejor viéndolo
-- (un enrojecimiento poco habitual, cómo quedó una zona...). Son internos del centro: el cliente no los ve.
--  · appointment_media: qué hay en cada cita (sin el contenido, para listar sin leer los ficheros).
--  · appointment_media_data: el fichero (foto reducida a JPEG de 1.600 px o vídeo tal cual, hasta 30 MB).

CREATE TABLE appointment_media (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT       NOT NULL,
    center_id       BIGINT       NOT NULL,
    kind            VARCHAR(10)  NOT NULL,
    content_type    VARCHAR(32)  NOT NULL,
    size_bytes      BIGINT       NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    uploaded_by_id  BIGINT,
    CONSTRAINT fk_appointment_media_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_appointment_media_center FOREIGN KEY (center_id) REFERENCES centers (id) ON DELETE CASCADE,
    CONSTRAINT fk_appointment_media_uploaded_by FOREIGN KEY (uploaded_by_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_appointment_media_appointment ON appointment_media (appointment_id);
CREATE INDEX ix_appointment_media_center ON appointment_media (center_id);

CREATE TABLE appointment_media_data (
    media_id  BIGINT NOT NULL PRIMARY KEY,
    data      BYTEA  NOT NULL,
    CONSTRAINT fk_appointment_media_data_media FOREIGN KEY (media_id) REFERENCES appointment_media (id) ON DELETE CASCADE
);
