-- «¿Olvidaste tu contraseña?»: enlaces de un solo uso para poner una contraseña nueva desde el correo.
-- Solo se guarda la huella SHA-256 del enlace; caducan a la hora (PasswordResetService.VALIDITY).

CREATE TABLE password_resets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    used_at     TIMESTAMP(6),
    CONSTRAINT uk_password_resets_token UNIQUE (token_hash),
    CONSTRAINT fk_password_resets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_password_resets_user ON password_resets (user_id);
