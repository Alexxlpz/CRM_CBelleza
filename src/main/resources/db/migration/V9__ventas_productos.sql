-- Productos que el centro vende a cada cliente. Al registrar una venta se resta del stock del centro.
-- unit_price guarda el precio del momento: si el producto cambia de precio, el historial no cambia.

CREATE TABLE product_sales (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id  BIGINT           NOT NULL,
    client_id  BIGINT           NOT NULL,
    product_id BIGINT           NOT NULL,
    worker_id  BIGINT,
    quantity   INTEGER          NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL,
    sold_at    TIMESTAMP(6)     NOT NULL,
    CONSTRAINT ck_product_sales_quantity CHECK (quantity > 0),
    CONSTRAINT fk_product_sales_center FOREIGN KEY (center_id) REFERENCES centers (id),
    CONSTRAINT fk_product_sales_client FOREIGN KEY (client_id) REFERENCES users (id),
    CONSTRAINT fk_product_sales_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_product_sales_worker FOREIGN KEY (worker_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_product_sales_center_client ON product_sales (center_id, client_id);
