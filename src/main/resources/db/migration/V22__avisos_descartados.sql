-- Avisos de la campana que cada usuario ha quitado («Marcar como visto» o «Limpiar todas»).
--  · Los avisos se calculan al vuelo; aquí solo se guarda la huella (texto + enlace) de los que ya ha visto.
--  · Si el aviso cambia (otra cantidad, otro día...) la huella es distinta y vuelve a salir.
--  · Las huellas de avisos que ya no existen se borran solas la próxima vez que se pinta la campana.

CREATE TABLE notification_dismissals (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL,
    notification_key VARCHAR(64) NOT NULL,
    dismissed_at     TIMESTAMP   NOT NULL,
    CONSTRAINT uq_notification_dismissals UNIQUE (user_id, notification_key),
    CONSTRAINT fk_notification_dismissals_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
