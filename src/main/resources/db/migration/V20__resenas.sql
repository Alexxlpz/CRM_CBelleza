-- Reseñas verificadas: solo las deja el cliente de una cita completada, una por cita.
--  · rating: de 1 a 5 estrellas; comment opcional.
--  · reply / replied_at: respuesta pública del centro (la escribe el dueño).
--  · center_id se guarda también aquí para sacar la nota de cada centro sin pasar por las citas.

CREATE TABLE reviews (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT        NOT NULL,
    center_id      BIGINT        NOT NULL,
    client_id      BIGINT        NOT NULL,
    rating         INT           NOT NULL,
    comment        VARCHAR(1000),
    created_at     TIMESTAMP(6)  NOT NULL,
    reply          VARCHAR(1000),
    replied_at     TIMESTAMP(6),
    CONSTRAINT uk_reviews_appointment UNIQUE (appointment_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_reviews_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_center FOREIGN KEY (center_id) REFERENCES centers (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_client FOREIGN KEY (client_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_reviews_center ON reviews (center_id, created_at);
CREATE INDEX ix_reviews_client ON reviews (client_id);
