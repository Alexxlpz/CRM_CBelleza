-- Alta de centros desde /alta-centro: el centro se crea con su equipo y queda oculto hasta que Cuquora lo revisa.
--  · published: si sale en el buscador y el mapa y si se puede reservar. Los centros que ya existían siguen publicados.
--  · tax_id: CIF o NIF que se revisa antes de publicar.
--  · approval_token_hash: huella del enlace «Publicar centro» del correo a administración (nulo cuando ya está publicado).
-- account_invitations: enlaces para que cada trabajador ponga su contraseña. Solo se guarda la huella del enlace.

ALTER TABLE centers ADD COLUMN published BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE centers ADD COLUMN tax_id VARCHAR(20);
ALTER TABLE centers ADD COLUMN approval_token_hash VARCHAR(64);
ALTER TABLE centers ADD COLUMN registered_at TIMESTAMP(6);
ALTER TABLE centers ADD CONSTRAINT uk_centers_approval_token UNIQUE (approval_token_hash);

CREATE TABLE account_invitations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    used_at     TIMESTAMP(6),
    CONSTRAINT uk_account_invitations_token UNIQUE (token_hash),
    CONSTRAINT fk_account_invitations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX ix_account_invitations_user ON account_invitations (user_id);
