-- Horario de cada profesional: tramos de la semana en los que trabaja (1 = lunes ... 7 = domingo).
--  · Un profesional sin tramos trabaja siempre que el centro está abierto (lo de siempre).
--  · Con tramos, solo se le pueden dar citas dentro de ellos, y siempre dentro del horario del centro.
--  · Dos tramos el mismo día = jornada partida. Lo cambia el dueño del centro en «Mi Centro» → Equipo.

CREATE TABLE worker_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id   BIGINT NOT NULL,
    day_of_week INT    NOT NULL,
    starts_at   TIME   NOT NULL,
    ends_at     TIME   NOT NULL,
    CONSTRAINT ck_worker_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_worker_hours_range CHECK (ends_at > starts_at),
    CONSTRAINT fk_worker_hours_worker FOREIGN KEY (worker_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_worker_hours_worker ON worker_hours (worker_id, day_of_week);
