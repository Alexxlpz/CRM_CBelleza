-- Agenda flexible:
--  · Cabinas por centro: varios trabajadores pueden atender a la vez si hay cabinas libres.
--  · Estados nuevos de cita: PROPOSED (el centro propone otras horas) y CANCELLED (anulada).
--  · Seguimiento de cambios para las campanas y los correos (último cambio, hora anterior, recordatorio).
--  · Propuestas de hora y bloqueos de agenda (vacaciones, descansos, cierres).
--  · Última vez que cada usuario abrió su campana de avisos.

ALTER TABLE centers ADD COLUMN cabins INT DEFAULT 1 NOT NULL;

ALTER TABLE appointments DROP CONSTRAINT ck_appointments_status;
ALTER TABLE appointments ADD CONSTRAINT ck_appointments_status
    CHECK (status IN ('PENDING', 'PROPOSED', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'COMPLETED'));

ALTER TABLE appointments ADD COLUMN created_at TIMESTAMP(6);
ALTER TABLE appointments ADD COLUMN last_change VARCHAR(30);
ALTER TABLE appointments ADD COLUMN last_change_at TIMESTAMP(6);
ALTER TABLE appointments ADD COLUMN previous_date_time TIMESTAMP(6);
ALTER TABLE appointments ADD COLUMN proposal_expires_at TIMESTAMP(6);
ALTER TABLE appointments ADD COLUMN reminder_sent_at TIMESTAMP(6);
ALTER TABLE appointments ADD COLUMN google_event_owner_id BIGINT;

UPDATE appointments SET created_at = date_time;

CREATE TABLE appointment_proposals (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT       NOT NULL,
    date_time      TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_appointment_proposals_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE
);
CREATE INDEX ix_appointment_proposals_appointment ON appointment_proposals (appointment_id);

-- worker_id nulo = bloqueo de todo el centro (cierre); con trabajador = solo esa persona no está disponible.
CREATE TABLE agenda_blocks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    center_id     BIGINT       NOT NULL,
    worker_id     BIGINT,
    starts_at     TIMESTAMP(6) NOT NULL,
    ends_at       TIMESTAMP(6) NOT NULL,
    reason        VARCHAR(255),
    created_by_id BIGINT,
    CONSTRAINT ck_agenda_blocks_range CHECK (ends_at > starts_at),
    CONSTRAINT fk_agenda_blocks_center FOREIGN KEY (center_id) REFERENCES centers (id),
    CONSTRAINT fk_agenda_blocks_worker FOREIGN KEY (worker_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_agenda_blocks_created_by FOREIGN KEY (created_by_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_agenda_blocks_center ON agenda_blocks (center_id, starts_at);

ALTER TABLE users ADD COLUMN notifications_seen_at TIMESTAMP(6);
