-- Registro de lo que aporta cada centro de Cuquora: qué código, qué huecos rellenó y cuándo.
--  · center_id es solo el número del centro en Cuquora (ningún otro dato suyo). Nulo si llegó sin él.
--  · created = true si ese centro dio de alta el producto (el resto solo rellenó huecos).
--  · Si se borra el producto, se borra también su registro.

CREATE TABLE product_contributions (
    id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gtin        VARCHAR(14)   NOT NULL,
    center_id   BIGINT,
    created     BOOLEAN       NOT NULL,
    fields      VARCHAR(120)  NOT NULL,
    created_at  TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_product_contributions_product FOREIGN KEY (gtin) REFERENCES products (gtin) ON DELETE CASCADE
);

CREATE INDEX idx_product_contributions_center ON product_contributions (center_id);
CREATE INDEX idx_product_contributions_gtin ON product_contributions (gtin);
